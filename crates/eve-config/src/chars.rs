    fn 結合文字() {
        for c in [
            '\u{0300}',
            '\u{0301}',
            '\u{0489}',
            '\u{20DD}',
            '\u{3099}',
            '\u{1E944}',
            '\u{E01EF}',
        ] {
            assert!(is_combining_mark(c), "U+{:04X}", u32::from(c));
        }
        // Mc (例: デーヴァナーガリーの母音記号 U+093E)・基底の文字・ZWJ は数えない
        for c in ['a', 'あ', '\u{093E}', '\u{200D}', '\u{FF9E}'] {
            assert!(!is_combining_mark(c), "U+{:04X}", u32::from(c));
        }
    }
