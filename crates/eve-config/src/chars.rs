//! 文字の分類の表 (docs/07 §17.4 の検査 4・5、§4.3 の無害化)。
//!
//! eve-text は Unicode の性質の表を持たない (幅と書記素の近似だけ。eve-text の `width.rs`) ので、検査に要る 2 つの性質を
//! ここに置く。依存を足さずに済むよう、どちらも範囲の表で持つ。版は eve-text の書記素の表と同じ Unicode 17.0.0
//! (試験の `TABLE_UNICODE_VERSION` が `eve_text::GRAPHEME_JOIN_UNICODE_VERSION` と一致することを確かめる)。
//! - `FORMAT`: 一般カテゴリ Cf (書式文字) と `Default_Ignorable_Code_Point` の和。
//! - `MARKS`: 一般カテゴリ Mn・Me (結合文字)。
//!
//! **表の作り直しの手順**: eve-text の表を新しい版にするときに、同じ版の `UnicodeData.txt` と
//! `DerivedCoreProperties.txt` (unicode.org の `Public/<版>/ucd/`) から、次の Python の出力に貼り替え、
//! 試験の `TABLE_UNICODE_VERSION` を直す。
//!
//! ```text
//! cat, first, dicp = {}, None, set()
//! for line in open("UnicodeData.txt", encoding="utf-8"):
//!     f = line.split(";"); cp = int(f[0], 16)
//!     if f[1].endswith(", First>"): first = cp; continue
//!     for c in range(first if f[1].endswith(", Last>") else cp, cp + 1): cat[c] = f[2]
//! for line in open("DerivedCoreProperties.txt", encoding="utf-8"):
//!     p = [x.strip() for x in line.split("#")[0].split(";")]
//!     if len(p) < 2 or p[1] != "Default_Ignorable_Code_Point": continue
//!     a, _, b = p[0].partition(".."); dicp.update(range(int(a, 16), int(b or a, 16) + 1))
//! def ranges(pred):
//!     out, start = [], None
//!     for cp in range(0x110001):
//!         ok = cp < 0x110000 and pred(cp)
//!         if ok and start is None: start = cp
//!         if not ok and start is not None: out.append((start, cp - 1)); start = None
//!     return ", ".join("(0x%04X, 0x%04X)" % r for r in out)
//! print(ranges(lambda c: cat.get(c) == "Cf" or c in dicp))   # FORMAT
//! print(ranges(lambda c: cat.get(c) in ("Mn", "Me")))        # MARKS
//! ```

use std::cmp::Ordering;

/// 言語ファイルの文言に使えない文字の種類 (07 §17.4 の検査 4・5)。診断の理由の語を選ぶのに使う。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CharClass {
    /// C0 (タブ・改行を含む)・DEL・C1 と、行・段落の区切り (U+2028 / U+2029)。
    Control,
    /// 書式文字 (Cf) と `Default_Ignorable_Code_Point` (ZWJ・ZWNJ を除く)。双方向の書式文字・方向の印・異体字セレクタ・
    /// タグ文字を含む。
    Format,
    /// 私用領域 (U+E000〜U+F8FF と第 15・16 面)。
    PrivateUse,
    /// 非文字 (U+FDD0〜U+FDEF と各面の U+xFFFE / U+xFFFF)。
    Noncharacter,
    /// 結合文字 (Mn・Me) が続きすぎる (検査 5)。
    CombiningMarks,
}

/// 言語ファイルの文言に使えない文字なら、その種類 (07 §17.4 の検査 4)。ファイル由来の文字列の無害化 (§4.3) も
/// この範囲を `<U+XXXX>` にする。結合文字の数 (検査 5) は文字 1 つでは決まらないので、ここでは返さない。
pub fn forbidden_char(c: char) -> Option<CharClass> {
    let cp = u32::from(c);
    // よくある場合を表を引かずに決める: ASCII の印字できる文字と、かな・CJK 統合漢字 (どの種類にも当たらない)
    if (0x20..0x7F).contains(&cp)
        || (0x3041..=0x30FF).contains(&cp)
        || (0x4E00..=0x9FFF).contains(&cp)
    {
        return None;
    }
    // char::is_control は一般カテゴリ Cc (C0・DEL・C1) と同じ
    if c.is_control() || matches!(c, '\u{2028}' | '\u{2029}') {
        return Some(CharClass::Control);
    }
    if (0xFDD0..=0xFDEF).contains(&cp) || cp & 0xFFFE == 0xFFFE {
        return Some(CharClass::Noncharacter);
    }
    if (0xE000..=0xF8FF).contains(&cp) || cp >= 0xF_0000 {
        return Some(CharClass::PrivateUse);
    }
    if is_joiner(c) {
        // ZWNJ・ZWJ は許す: U+FE0F を含まない絵文字の ZWJ 列と、ペルシア語・インド系の文字などの正しい綴りに要り、
        // 表示を偽装する働きが無い
        return None;
    }
    in_ranges(cp, FORMAT).then_some(CharClass::Format)
}

/// ZWNJ (U+200C) か ZWJ (U+200D)。
pub(crate) fn is_joiner(c: char) -> bool {
    matches!(c, '\u{200C}' | '\u{200D}')
}

/// 一般カテゴリが Mn か Me (結合文字) か。
pub(crate) fn is_combining_mark(c: char) -> bool {
    let cp = u32::from(c);
    // 結合文字は U+0300 から (よくある ASCII・ラテン文字で表を引かない)
    cp >= 0x0300 && in_ranges(cp, MARKS)
}

fn in_ranges(cp: u32, table: &[(u32, u32)]) -> bool {
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < cp {
                Ordering::Less
            } else if lo > cp {
                Ordering::Greater
            } else {
                Ordering::Equal
            }
        })
        .is_ok()
}

